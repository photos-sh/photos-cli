package cli

import (
	"context"
	"fmt"
	"sort"
	"strings"
)

// completionCommand writes a shell script that completes commands and flags.
//
// The script is generated from the real command tree, so a command or a flag
// added later is completed without anybody remembering to. It completes
// nothing that needs the network; after the commands and flags it falls
// back to file names, which is what most arguments here are.
func completionCommand() *Command {
	return &Command{
		Name:    "completion",
		Group:   groupOther,
		Summary: "write a shell completion script",
		Args:    "bash|zsh|fish",
		Long: `Completes command names, subcommands and flags, and file names after
them. The script is written to standard output:

    # bash, this session
    source <(photos completion bash)
    # bash, every session
    photos completion bash > ~/.local/share/bash-completion/completions/photos

    # zsh, somewhere on $fpath
    photos completion zsh > "${fpath[1]}/_photos"

    # fish
    photos completion fish > ~/.config/fish/completions/photos.fish`,
		Examples: []string{
			"source <(photos completion bash)",
			"photos completion fish > ~/.config/fish/completions/photos.fish",
		},
		Run: func(ctx context.Context, env *Env, args []string) error {
			if len(args) != 1 {
				return usagef("name a shell: bash, zsh or fish")
			}
			nodes := describeTree(Root())
			switch args[0] {
			case "bash":
				fmt.Fprint(env.Out, bashCompletion(nodes))
			case "zsh":
				fmt.Fprint(env.Out, zshCompletion(nodes))
			case "fish":
				fmt.Fprint(env.Out, fishCompletion(nodes))
			default:
				return usagef("no completion for %q: bash, zsh or fish", args[0])
			}
			return nil
		},
	}
}

// completionNode is one command, flattened for a shell to read.
type completionNode struct {
	// Path is the words that reach it, without the binary: "jobs create".
	// Empty for the root. A command reached by an alias has a node of its
	// own.
	Path []string
	// Subcommands are the words that may follow, sorted.
	Subcommands []string
	// Flags are the flags it accepts, sorted, with their dashes.
	Flags []string
}

// describeTree flattens the command tree, and returns the flags that take a
// value in the first node's company: a shell has to skip a value to find
// the command's words.
func describeTree(root *Command) []completionNode {
	var nodes []completionNode
	var walk func(cmd *Command, path []string)
	walk = func(cmd *Command, path []string) {
		node := completionNode{Path: path, Subcommands: cmd.childNames()}
		for _, f := range append(commandFlags(cmd), globalFlags()...) {
			node.Flags = append(node.Flags, "--"+f.Name)
		}
		sort.Strings(node.Flags)
		nodes = append(nodes, node)
		for _, child := range cmd.Children {
			for _, name := range append([]string{child.Name}, child.Aliases...) {
				walk(child, append(append([]string{}, path...), name))
			}
		}
	}
	walk(root, nil)
	return nodes
}

// valueFlags is every flag in the tree that takes a value, in both
// spellings, sorted: "--out-dir", "-o".
func valueFlags(root *Command) []string {
	seen := map[string]bool{}
	var walk func(cmd *Command)
	walk = func(cmd *Command) {
		for _, f := range append(commandFlags(cmd), globalFlags()...) {
			if f.Placeholder == "" {
				continue
			}
			seen["--"+f.Name] = true
			if f.Short != "" {
				seen["-"+f.Short] = true
			}
		}
		for _, child := range cmd.Children {
			walk(child)
		}
	}
	walk(root)
	flags := make([]string, 0, len(seen))
	for f := range seen {
		flags = append(flags, f)
	}
	sort.Strings(flags)
	return flags
}

func (n completionNode) words() string {
	return strings.Join(append(append([]string{}, n.Subcommands...), n.Flags...), " ")
}

// bashCompletion is a script with one case statement keyed on the command
// path. The labels are quoted: `jobs create)` unquoted is a syntax error.
func bashCompletion(nodes []completionNode) string {
	var b strings.Builder
	b.WriteString(`# photos completion for bash. Generated by 'photos completion bash'.
#
# Completes command names, subcommands and flags, then file names. Nothing
# here reaches the network.

_photos() {
    local cur key words i
    local -a path
    cur="${COMP_WORDS[COMP_CWORD]}"
    COMPREPLY=()

    # The command path is the words before the cursor that are not flags,
    # minus the binary. The value of a flag that takes one is skipped.
    path=()
    i=1
    while (( i < COMP_CWORD )); do
        case "${COMP_WORDS[i]}" in
            ` + strings.Join(valueFlags(Root()), "|") + `) (( i++ )) ;;
            -*) ;;
            *) path+=("${COMP_WORDS[i]}") ;;
        esac
        (( i++ ))
    done

    # Only the words that name commands: a file name ends the path.
    words=""
    key=""
    for (( i = 0; i < ${#path[@]}; i++ )); do
        case "$(_photos_words "${key:+$key }${path[i]}")" in
            "") break ;;
            *) key="${key:+$key }${path[i]}" ;;
        esac
    done
    words="$(_photos_words "$key")"

    if [[ "$cur" == -* || ( -n "$words" && "$words" != -* ) ]]; then
        COMPREPLY=($(compgen -W "$words" -- "$cur"))
    fi
}

# The words that may follow a command path; nothing for a path that names no
# command.
_photos_words() {
    case "$1" in
`)
	for _, node := range nodes {
		fmt.Fprintf(&b, "        %q) echo %q ;;\n", strings.Join(node.Path, " "), node.words())
	}
	b.WriteString(`    esac
}

# -o default: file names when nothing above matched.
complete -o default -F _photos photos
`)
	return b.String()
}

// zshCompletion is the same walk in zsh's idiom.
func zshCompletion(nodes []completionNode) string {
	var b strings.Builder
	b.WriteString(`#compdef photos
# photos completion for zsh. Generated by 'photos completion zsh'.
#
# Completes command names, subcommands and flags, then file names. Nothing
# here reaches the network.

_photos_words() {
    case "$1" in
`)
	for _, node := range nodes {
		fmt.Fprintf(&b, "        %q) echo %q ;;\n", strings.Join(node.Path, " "), node.words())
	}
	b.WriteString(`    esac
}

_photos() {
    local key="" word candidate found
    local -a cmdpath
    local i=2

    # The words before the cursor that are not flags, minus the binary. The
    # value of a flag that takes one is skipped.
    while (( i < CURRENT )); do
        word="${words[i]}"
        case "$word" in
            ` + strings.Join(valueFlags(Root()), "|") + `) (( i++ )) ;;
            -*) ;;
            *) cmdpath+=("$word") ;;
        esac
        (( i++ ))
    done

    # Only the words that name commands: a file name ends the path.
    for word in "${cmdpath[@]}"; do
        candidate="${key:+$key }$word"
        [[ -n "$(_photos_words "$candidate")" ]] || break
        key="$candidate"
    done

    found="$(_photos_words "$key")"
    if [[ "${words[CURRENT]}" == -* || ( -n "$found" && "$found" != -* ) ]]; then
        compadd -- ${=found}
    else
        _files
    fi
}

_photos "$@"
`)
	return b.String()
}

// fishCompletion is a list of rules: fish has no case statement to key on,
// so each command's words are guarded by the commands seen so far.
func fishCompletion(nodes []completionNode) string {
	var b strings.Builder
	b.WriteString(`# photos completion for fish. Generated by 'photos completion fish'.
#
# Completes command names, subcommands and flags; fish adds file names
# itself. Nothing here reaches the network.

`)
	var first []string
	for _, node := range nodes {
		if len(node.Path) == 0 {
			first = node.Subcommands
		}
	}
	for _, node := range nodes {
		condition := "not __fish_seen_subcommand_from " + strings.Join(first, " ")
		if len(node.Path) > 0 {
			condition = "__fish_seen_subcommand_from " + strings.Join(node.Path, "; and __fish_seen_subcommand_from ")
		}
		for _, word := range node.Subcommands {
			fmt.Fprintf(&b, "complete -c photos -n %q -a %q\n", condition, word)
		}
		for _, word := range node.Flags {
			fmt.Fprintf(&b, "complete -c photos -n %q -l %q\n", condition, strings.TrimPrefix(word, "--"))
		}
	}
	return b.String()
}
